// Measure (Post-v0.255.1, Mario: "Yes, measure first"): what in the four race-plan tables is a classic session format
// anyone may prescribe, and what is the source's own arrangement (which week holds which session, the long-run and
// recovery sequences, sessions reused across plans). No ruling, no fix: the before-picture for the derivation ruling.
//
//   node tests/measure/race-plans_source-fingerprint.js            prints the summary; writes the row table to
//                                                                  tests/measure/race-plans_source-fingerprint.md
//
// Reads the four tables out of the built page through the harness (the half and marathon tables are not exported by the
// module, and tools/same-script.mjs proves the page is the sources token for token). The blast radius walks tests/ and
// docs/decisions for every exact table string it finds.
const { readFileSync, readdirSync, statSync, writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');
const { load } = require('../harness.js');

const REPO = join(__dirname, '..', '..');
const PAGE = join(REPO, 'dist-github-pages', 'index.html');
const OUT = join(__dirname, 'race-plans_source-fingerprint.md');

/** The classic format a speed session's structure belongs to, read from its detail. */
function format(detail) {
  const h = detail.split('\n')[0];
  const body = detail.toLowerCase();
  if (/fartlek/i.test(h)) return 'fartlek';
  if (/^hill workout/i.test(h)) return 'hills';
  if (/progression tempo/i.test(h)) return 'progression tempo';
  if (/tempo/i.test(h)) return 'tempo';
  if (/ladder|pyramid/i.test(h)) return 'ladder or pyramid';
  if (/^\d+ × \d+:\d\d at \w+ Pace/i.test(h)) return 'reps at one pace';
  if (/rounds|bursts|bookends|blocks|kicker|chased|floats|then/i.test(h) || body.includes('rounds of')) return 'mixed-pace set';
  return 'other';
}

/** Walks a folder for files, by extension. */
function files(dir, exts, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === 'node_modules' || name === 'snapshots') continue;
    if (statSync(p).isDirectory()) files(p, exts, out);
    else if (exts.some((e) => name.endsWith(e))) out.push(p);
  }
  return out;
}

(async () => {
  const IA = load(PAGE);
  const tables = { '5K': IA.eval('NRC_5K_TABLE'), '10K': IA.eval('NRC_10K_TABLE'), half: IA.eval('NRC_HALF_TABLE'), marathon: IA.eval('NRC_MARATHON_TABLE') };
  const md = [];
  const summary = [];
  const sessions = new Map(); // detail -> [{plan, week, slot}]
  let rows = 0;
  let speedCount = 0;
  const strings = new Set(); // exact table strings for the blast radius

  md.push('# Race plans: the source fingerprint (measure, Post-v0.255.1)', '');
  md.push('Generated by `tests/measure/race-plans_source-fingerprint.js` from the four tables of `core/src/engine/nrc-race-bike-swim.ts`, read out of the built page.', '');
  for (const [plan, table] of Object.entries(tables)) {
    md.push(`## ${plan}: ${table.length} weeks`, '', '| Wk | Long run | Flags | Speed sessions (format: headline) | Recovery runs |', '|---|---|---|---|---|');
    const longs = [];
    const formats = [];
    const recov = [];
    table.forEach((row, i) => {
      rows++;
      const flags = ['race', 'rehearsal', 'peak', 'taper', 'cutback', 'hold'].filter((f) => row.long[f]).join(' ');
      const speeds = row.speed.map((s, k) => {
        speedCount++;
        const f = format(s.detail);
        const list = sessions.get(s.detail) || [];
        list.push({ plan, week: i + 1, slot: k + 1 });
        sessions.set(s.detail, list);
        strings.add(s.detail.split('\n')[0]);
        return `${f}: ${s.detail.split('\n')[0]}`;
      });
      strings.add(row.long.label);
      longs.push(`${row.long.val}${row.long.unit === 'min' ? 'min' : 'mi'}${row.long.cutback ? '↓' : ''}${row.long.hold ? '=' : ''}`);
      formats.push(row.speed.map((s) => format(s.detail)).join('+'));
      recov.push(row.recovery.map((r) => (typeof r === 'number' ? `${r}` : `${r.mi}mi`)).join('/'));
      md.push(`| ${i + 1} | ${row.long.val} ${row.long.unit} (${row.long.label}) | ${flags} | ${speeds.join('<br>')} | ${row.recovery.map((r) => (typeof r === 'number' ? `${r} min` : `${r.mi} mi`)).join(', ')} |`);
    });
    md.push('', `- **Long-run sequence:** ${longs.join(' → ')}`, `- **Speed-format sequence:** ${formats.join(' → ')}`, `- **Recovery sequence:** ${recov.join(' | ')}`, '');
    summary.push(`${plan}: ${table.length} weeks, ${table.reduce((n, r) => n + r.speed.length, 0)} speed sessions; long runs ${longs.join(' → ')}`);
  }

  // Cross-plan reuse: the same session text in more than one plan.
  const reused = [...sessions.entries()].filter(([, where]) => new Set(where.map((w) => w.plan)).size > 1);
  const byFormat = {};
  for (const [detail] of sessions) byFormat[format(detail)] = (byFormat[format(detail)] || 0) + 1;
  md.push('## The session library', '', `${speedCount} speed-session slots across the four plans hold ${sessions.size} distinct sessions; ${reused.length} of those appear in more than one plan:`, '');
  for (const [detail, where] of reused) md.push(`- "${detail.split('\n')[0]}": ${where.map((w) => `${w.plan} W${w.week}`).join(', ')}`);
  md.push('', 'Distinct sessions by classic format:', '', ...Object.entries(byFormat).sort((a, b) => b[1] - a[1]).map(([f, n]) => `- ${f}: ${n}`), '');

  // Blast radius: every exact table string found in tests/ (not snapshots) and docs/decisions.
  const targets = [...files(join(REPO, 'tests'), ['.ts', '.js']), ...files(join(REPO, 'docs', 'decisions'), ['.md'])].filter((p) => !p.includes('/measure/'));
  const hits = {};
  for (const p of targets) {
    const text = readFileSync(p, 'utf8');
    for (const s of strings) if (text.includes(s)) (hits[relative(REPO, p)] = hits[relative(REPO, p)] || []).push(s);
  }
  const snap = JSON.parse(readFileSync(join(REPO, 'tests', 'snapshots', 'program-output.json'), 'utf8'));
  const lattice = JSON.parse(readFileSync(join(REPO, 'tests', 'snapshots', 'program-output-lattice.json'), 'utf8'));
  const raceKeys = (o) => Object.keys(o).filter((k) => /5k|10k|half|marathon/i.test(k));
  md.push('## Blast radius', '', `Files outside the snapshots and measure folder that quote an exact table string (${strings.size} strings looked for):`, '');
  for (const [p, list] of Object.entries(hits).sort()) md.push(`- ${p}: ${list.length} string(s), e.g. "${list[0]}"`);
  md.push('', `Snapshots: ${raceKeys(snap.programs).length} of ${Object.keys(snap.programs).length} program-output entries are race goals (${raceKeys(snap.programs).join('; ')}); ${raceKeys(lattice).length} of ${Object.keys(lattice).length} lattice entries name a race goal.`, '');
  writeFileSync(OUT, md.join('\n'));

  console.log(summary.join('\n'));
  console.log(`rows ${rows}, speed slots ${speedCount}, distinct sessions ${sessions.size}, reused across plans ${reused.length}`);
  console.log('formats:', JSON.stringify(byFormat));
  console.log(`blast radius: ${Object.keys(hits).length} files quote a table string; race-goal snapshot entries ${raceKeys(snap.programs).length}/${Object.keys(snap.programs).length}, lattice ${raceKeys(lattice).length}/${Object.keys(lattice).length}`);
  for (const [p, list] of Object.entries(hits).sort()) console.log(`  ${p}: ${list.length}`);
  console.log(`report: ${relative(REPO, OUT)}`);
})();
